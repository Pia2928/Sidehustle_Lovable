-- Run in Supabase (SQL editor) or as a Lovable migration. All tables are locked (RLS on, no policies):
-- only the "api" edge function (service role) reads or writes them. Participants never touch the database directly.

create table if not exists participants (
  pid text primary key, condition text not null, idea_index int not null, src text,
  first_seen timestamptz not null default now(), last_seen timestamptz not null default now()
);
create table if not exists allocation (
  slot int primary key, block int not null, condition text not null, pid text unique, assigned_at timestamptz
);
create table if not exists canvas (
  pid text primary key references participants(pid), boxes jsonb not null default '{}'::jsonb,
  started_at timestamptz, updated_at timestamptz not null default now(),
  submitted_at timestamptz, how_submitted text, complete boolean not null default false
);
create table if not exists canvas_log (
  id bigserial primary key, pid text not null, box text not null, text text not null, created_at timestamptz not null default now()
);
create table if not exists messages (
  id bigserial primary key, pid text not null, role text not null, content text not null, model text,
  box text, suggestions jsonb, kind text, created_at timestamptz not null default now()
);
create table if not exists events (
  id bigserial primary key, pid text not null, page text, event_type text not null, detail text, created_at timestamptz not null default now()
);
create index if not exists idx_messages_pid on messages (pid, id);
create index if not exists idx_log_pid on canvas_log (pid, id);
create index if not exists idx_events_pid on events (pid, id);

alter table participants enable row level security;
alter table allocation   enable row level security;
alter table canvas       enable row level security;
alter table canvas_log   enable row level security;
alter table messages     enable row level security;
alter table events       enable row level security;

-- Balanced assignment: the next free slot of a pre-generated permuted-block sequence (block sizes 4 and 8).
-- A returning participant gets the original slot back. The advisory lock means two participants never share a slot.
create or replace function assign_condition(p_pid text) returns text
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  perform pg_advisory_xact_lock(424242);
  select * into r from allocation where pid = p_pid;
  if found then return r.condition; end if;
  select * into r from allocation where pid is null order by slot limit 1;
  if not found then raise exception 'Allocation sequence exhausted'; end if;
  update allocation set pid = p_pid, assigned_at = now() where slot = r.slot;
  return r.condition;
end $$;
revoke all on function assign_condition(text) from public, anon, authenticated;

